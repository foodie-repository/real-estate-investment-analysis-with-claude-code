from projects.chapter05_roi.sheets import (
    _build_headers,
    _build_metadata,
    _row_from_data,
)


def test_build_metadata_matches_sheet_labels_and_period_units():
    assert _build_metadata(
        202201,
        [2, 4],
        "2026-08-05 16:39:53",
    ) == (
        "매수 시점: 2022.1 | 비교 기간: 2년, 4년 | "
        "마지막 업데이트: 2026-08-05 16:39:53"
    )


